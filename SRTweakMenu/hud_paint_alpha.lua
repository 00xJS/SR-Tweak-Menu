local values={}
for i,rows in ipairs(masks) do
 values[i]={}
 for y,row in ipairs(rows) do for x=1,64 do values[i][(y-1)*64+x]=tonumber(row:sub(x,x),16)/15 end end
end
return function(i,u,v)
 if u<0 or u>1 or v<0 or v>1 then return 0 end
 local x,y=u*63,v*63
 local a,b=math.floor(x),math.floor(y)
 local tx,ty=x-a,y-b
 local function pixel(xx,yy) return values[i][math.min(63,yy)*64+math.min(63,xx)+1] end
 return (pixel(a,b)*(1-tx)+pixel(a+1,b)*tx)*(1-ty)+(pixel(a,b+1)*(1-tx)+pixel(a+1,b+1)*tx)*ty
end
